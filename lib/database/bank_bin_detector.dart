  /// تشخیص بانک از شماره کارت (با یا بدون فاصله)
  static String? detectBank(String cardNumber) {
    final digits = cardNumber.replaceAll(RegExp(r'\D'), '');
    if (digits.length < 6) return null;
    final bin = digits.substring(0, 6);
    return _binToBank[bin];
  }

  static bool isKnownBin(String cardNumber) => detectBank(cardNumber) != null;

  /// لیست همه‌ی بانک‌های پشتیبانی‌شده
  static List<String> get supportedBanks {
    final banks = <String>{};
    for (final bank in _binToBank.values) {
      banks.add(bank);
    }
    return banks.toList();
  }
}
